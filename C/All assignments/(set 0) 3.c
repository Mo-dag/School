#include <stdio.h>

int main()
{
    int c;
    int a;    // Here we declare (deklarerar) the integer (heltals) variable a
    a = 7;   // Here we assign (tilldelar) it a value
    
    int b = -3;  // Both steps in one go, called initiation (initiering)
    
    printf("The value of a is %d\n", a);
    printf("The value of b is %d\n", b);
    printf("The value of c is %d\n", c);
}
